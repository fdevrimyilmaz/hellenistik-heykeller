  /** @param {Sculpture} first @param {Sculpture} second */
  function compare(first, second) {
    const rows = fields
      .map((f) => ({
        ...f,
        a: first.features[f.id] ?? null,
        b: second.features[f.id] ?? null,
      }))
      .map((r) => ({
        ...r,
        status:
          r.a === null || r.b === null
            ? "Bilinmiyor"
            : r.a === r.b
              ? "Ortak"
              : "Farklı",
      }));
    const valid = rows.filter((r) => r.status !== "Bilinmiyor");
    const groups = ["İkonografi", "Biçim"].map((name) => {
      const rs = valid.filter((r) => r.group === name);
      return {
        name,
        count: rs.length,
        score: rs.length
          ? Math.round(
              (rs.filter((r) => r.status === "Ortak").length / rs.length) * 100,
            )
          : null,
      };
    });
    const same = first.id === second.id;
    if (same) for (const group of groups) group.score = null;
    return {
      rows,
      groups,
      same,
      count: valid.length,
      coverage: Math.round((valid.length / fields.length) * 100),
      score:
        !same && valid.length >= 3
          ? Math.round(
              (valid.filter((r) => r.status === "Ortak").length /
                valid.length) *
                100,
            )
          : null,
    };
  }
