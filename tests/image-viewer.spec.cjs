const { test, expect } = require('@playwright/test');
test('özgün çözünürlük, katalog araması ve mobil inceleme', async ({page}) => {
  await page.goto('/');
  await page.locator('.image-zoom-trigger').first().click();
  const viewer = page.locator('.image-viewer');
  await expect(viewer).toBeVisible();
  await expect.poll(() => page.locator('.image-viewer-stage img').evaluate(i => i.complete && i.naturalWidth > 0)).toBeTruthy();
  await page.locator('[data-action="native"]').click();
  const size = await page.locator('.image-viewer-stage img').evaluate(i => ({actual:i.naturalWidth, rendered:i.width, src:i.getAttribute('src')}));
  expect(size.rendered).toBe(size.actual);
  expect(size.src).toContain('/originals/');
  await page.keyboard.press('Escape');
  await expect(viewer).not.toBeVisible();
  await page.locator('#catalogSearch').fill('74.51.2694');
  await expect(page.locator('#catalogRecords > article:visible')).toHaveCount(1);
  await page.locator('#catalogSearch').fill('');
  await expect(page.locator('#catalogRecords > article:visible')).toHaveCount(12);
  await page.setViewportSize({width:390,height:844});
  await page.goto('/tarihsel-arka-plan.html');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.locator('.mobile-menu').click();
  await page.locator('.sidebar-close').click();
  await expect(page.locator('.sidebar')).not.toHaveClass(/open/);
  await page.locator('.image-zoom-trigger').first().click();
  await expect(viewer).toBeVisible();
  await expect.poll(() => page.locator('.image-viewer-stage img').evaluate(i => i.complete && i.naturalWidth > 0)).toBeTruthy();
  await page.locator('[data-action="fit"]').click();
  await page.locator('[data-action="in"]').click();
  await expect(page.locator('.image-viewer-toolbar output')).toHaveText('150%');
  await page.locator('[data-action="close"]').click();
  await expect(viewer).not.toBeVisible();
});
