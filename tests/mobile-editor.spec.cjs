const {test, expect} = require('@playwright/test');
const model = require('../research-model');
test('Expo metinleri ve alan gözlemleri yazılır, cihazda saklanır ve esere bağlı kalır', async ({page}) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({width:390,height:844});
  await page.goto('/mobile');
  const open = () => page.getByRole('button',{name:'Eksik Alanları Kodla',exact:true}).click();
  await open();
  await expect(page.getByLabel('İkonografi metni',{exact:true})).toHaveValue(/The Metropolitan/);
  await page.getByLabel('İkonografi metni',{exact:true}).fill('Araştırmacının ikonografi değerlendirmesi.');
  await page.getByLabel('Stil metni',{exact:true}).fill('Saç düzeni ve hacim ilişkisine ilişkin gözlem.');
  const observation = model.fields[0].label + ' gözlemi';
  await page.getByLabel(observation,{exact:true}).fill('Üç sıralı yaprak çelengi.');
  await page.getByRole('button',{name:'Metinleri kaydet',exact:true}).click();
  await expect(page.getByText('İkonografi, stil ve gözlemleriniz bu cihazda kaydedildi.',{exact:true})).toBeVisible();
  await page.reload(); await open();
  await expect(page.getByLabel('İkonografi metni',{exact:true})).toHaveValue('Araştırmacının ikonografi değerlendirmesi.');
  await expect(page.getByLabel('Stil metni',{exact:true})).toHaveValue('Saç düzeni ve hacim ilişkisine ilişkin gözlem.');
  await expect(page.getByLabel(observation,{exact:true})).toHaveValue('Üç sıralı yaprak çelengi.');
  await page.getByRole('button',{name:'Kapat',exact:true}).click();
  await page.getByRole('tab',{name:'Eser Fişi',exact:true}).click();
  await page.getByRole('button',{name:'Eser seç: Apollon başı',exact:true}).click();
  await page.getByRole('button',{name:/Afrodit — Venus de Milo/}).click();
  await page.getByRole('button',{name:'Eser fişi ve elle kodlama',exact:true}).click();
  await expect(page.getByLabel('İkonografi metni',{exact:true})).toHaveValue('');
  expect(errors).toEqual([]);
});

test('Kodlamayı kaydet eksik bilgiyi taslak kaydeder, tamamlanan kodlamayı yeniden yükler', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/mobile');
  await expect(page.getByRole('button',{name:'Eksik Alanları Kodla',exact:true})).toBeEnabled();
  await page.evaluate(records => {
    records[0].coder = 'Eski kayıt adı';
    records[0].codeHistory = [{coder:'Geçmiş adı',codingNote:'Korunan kaynak notu'}];
    localStorage.setItem('hellenistic-mobile-records-v1', JSON.stringify(records));
  }, JSON.parse(JSON.stringify(model.records)));
  await page.reload();
  const open = () => page.getByRole('button',{name:'Eksik Alanları Kodla',exact:true}).click();
  await open();
  await expect(page.getByLabel('Kodlayıcı adı',{exact:true})).toHaveCount(0);
  const migrated = await page.evaluate(() => JSON.parse(localStorage.getItem('hellenistic-mobile-records-v1')));
  expect(migrated[0]).not.toHaveProperty('coder');
  expect(migrated[0].codeHistory).toEqual([{codingNote:'Korunan kaynak notu'}]);
  await page.getByLabel('Kaynak ve kodlama gerekçesi',{exact:true}).fill('');
  await page.getByLabel('Stil metni',{exact:true}).fill('Taslak stil incelemesi');
  await page.getByRole('button',{name:'Kodlamayı kaydet',exact:true}).click();
  await expect(page.getByText(/^Taslak kaydedildi\. Eksik alanlar:/)).toBeVisible();
  await page.reload(); await open();
  await expect(page.getByLabel('Stil metni',{exact:true})).toHaveValue('Taslak stil incelemesi');
  await page.getByLabel('Kaynak ve kodlama gerekçesi',{exact:true}).fill('Met 74.51.2694: üç sıralı yaprak çelengi');
  await page.getByLabel('Kaynakça',{exact:true}).fill('Met, 74.51.2694, eser kaydı.');
  for (const field of model.fields) await page.getByLabel(field.label + ' gözlemi',{exact:true}).fill('Kaynak görseli incelendi; korunmayan ayrıntılar değerlendirilemiyor.');
  const feature = model.fields[0];
  const next = feature.options[(feature.options.indexOf(model.records[0].features[feature.id])+1)%feature.options.length];
  await page.getByRole('button',{name:feature.label + ': ' + model.records[0].features[feature.id],exact:true}).click();
  await page.getByRole('button',{name:'Kodlamayı kaydet',exact:true}).click();
  await expect(page.getByText('Doğrulandı. Tüm alanlar bu cihazda kaydedildi.',{exact:true})).toBeVisible();
  await page.reload(); await open();
  await expect(page.getByLabel('Kodlayıcı adı',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Kaynak ve kodlama gerekçesi',{exact:true})).toHaveValue('Met 74.51.2694: üç sıralı yaprak çelengi');
  await expect(page.getByRole('button',{name:feature.label + ': ' + next,exact:true})).toBeVisible();
});
